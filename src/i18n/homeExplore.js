export function formatExploreCount(lang, shown, total) {
  if (lang === 'en') {
    return `Showing ${shown} of ${total} verified stories`;
  }
  return `Menampilkan ${shown} dari ${total} kisah terverifikasi`;
}

export function formatStoryCount(lang, count) {
  if (lang === 'en') {
    return count === 1 ? '1 story' : `${count} stories`;
  }
  return `${count} kisah`;
}

export function formatConnectionCount(lang, count) {
  if (lang === 'en') {
    return count === 1 ? '1 connected link' : `${count} connected links`;
  }
  return `${count} kisah terhubung`;
}
